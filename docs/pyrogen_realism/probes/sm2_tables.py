            for md in M2:
                m = Dd.get(f'{pre}_{mo}_{md}')
                bb = b[md]
                if m is None or bb is None or m.get(key) is None or bb.get(key) is None:
                    out.append('-')
                else:
                    out.append(f"{abs(m[key]-bb[key])*1e3:.2f}")
