def calib_block(Kd, pre, title, note):
    print(f'### {title}\n')
    print(note + '\n')
    print('| case | model | k spread at T=756 (0.26..0.32): first / t50 / t90 [ms], peak [MPa] | T_ign spread at k=0.271 (756..950): first / t50 / t90 [ms], peak | combos that never light | gap P-C at nominal first / t50 / t90 |')
    print('|---|---|---|---|---|---|')
    for mo in MOTORS:
        nominal = {}
        for md in M2:
            def g(k, T):
                return Kd.get(f'{pre}_{mo}_{md}_k{k}_T{T}')

            def rng(items, key):
                v = [x.get(key) for x in items if x is not None and x.get(key) is not None and x['n_lit'] > 0]
                return (max(v) - min(v)) if len(v) > 1 else None
            ks = [g(k, 756) for k in KS]
            ts = [g(0.271, T) for T in TS]
            nev = sum(1 for k in KS for T in TS if g(k, T) is not None and g(k, T)['n_lit'] == 0)

            def fmt(items):
                out = [ms(rng(items, key)) for key in ('t_first', 't50', 't90')]
                pk = [x['peak'] for x in items if x is not None and x['n_lit'] > 0]
                return ' / '.join(out) + (f", {max(pk)-min(pk):.2f}" if len(pk) > 1 else '')
            nominal[md] = g(0.271, 756)
            print(f"| {LABEL[mo]} | {md} | {fmt(ks)} | {fmt(ts)} | {nev} of 9 | |")
        p, c = nominal.get('peretz'), nominal.get('conduction')
        if p and c:
            def d(key):
                return (p[key] - c[key]) if (p.get(key) is not None and c.get(key) is not None) else None
            print(f"| {LABEL[mo]} | gap P-C | | | | {ms(d('t_first'))} / {ms(d('t50'))} / {ms(d('t90'))} |")
    print()


