        def calib(vary):
            out = []
            for md in M2:
                if vary == 'k':
                    items = [KX.get(f'KX_{mo}_{md}_k{k}_T756') for k in KS]
                else:
                    items = [KX.get(f'KX_{mo}_{md}_k0.271_T{T}') for T in TS]
