def gap_table(prefix, D_, title):
    """Peretz-ODE minus conduction, closed loop vs open loop (mean/range over forcing sources) -> feedback share."""
    print(f'### {title}\n')
    print('Gap = (Peretz ODE) - (conduction), ms. closed = full runs; open = replay of the SAME recorded forcing '
          '(mean and range over the Peretz-ODE and conduction forcing sources; the range including the Goodman forcing is added); feedback = closed - mean(open).\n')
    print('| case | metric | closed gap | open gap (mean) [min..max over sources] | feedback share (closed - open) |')
    print('|---|---|---|---|---|')
    for mo in MOTORS:
        cp, cc = D_.get(f'{prefix}_{mo}_peretz'), D_.get(f'{prefix}_{mo}_conduction')
        if cp is None or cc is None:
            continue
        for key, lab in (('t_first', 'first'), ('t50', 't50'), ('t90', 't90'), ('dur90', 'dur90')):
            a, b = cp.get(key), cc.get(key)
            cl = (a - b) if (a is not None and b is not None) else None
            ops = []
            ops_all = []
            for src in M3:
                kp = OPEN.get((prefix, mo, src, 'peretz')); kc = OPEN.get((prefix, mo, src, 'conduction'))
                if kp and kc:
                    mk = {'t_first': 'first'}.get(key, key)
                    u, v = kp[0].get(mk), kc[0].get(mk)
                    if u is not None and v is not None and np.isfinite(u) and np.isfinite(v):
                        ops_all.append(u - v)
                        if src != 'goodman':
                            ops.append(u - v)
            if cl is None or not ops:
                print(f"| {LABEL[mo]} | {lab} | {ms(cl)} | - | - |")
                continue
            mean = float(np.mean(ops))
            print(f"| {LABEL[mo]} | {lab} | {ms(cl)} | {ms(mean)} [{ms(min(ops))} .. {ms(max(ops))}]; incl. Goodman forcing [{ms(min(ops_all))} .. {ms(max(ops_all))}] | {ms(cl - mean)} |")
    print()


