OPEN = {}


def open_loop(D_, prefix, srcs, title):
    print(f'### {title}\n')
    print('Rows = forcing source (the closed-loop run whose recorded surface forcing is replayed); columns = solid model replayed on it. '
          'Cells = first / t50 / t90 / t90-first [ms], never-lit in the replay window. The diagonal equals the closed-loop run '
          '(self-replay check: max |dt| shown).\n')
    for mo in MOTORS:
        print(f'**{LABEL[mo]}**\n')
        print('| forcing from | window [ms] | replay goodman | replay peretz | replay conduction | self-replay max abs dt [s] |')
        print('|---|---|---|---|---|---|')
        for src in srcs:
            tag = f'{prefix}_{mo}_{src}'
            m = D_.get(tag)
            if m is None or not (DATA / f'{tag}_forcing.npz').exists():
                continue
            z = np.load(DATA / f'{tag}_forcing.npz')
            fo = {'h': z['h'], 'T_drv': z['Td'], 't': z['t'], 'dt': z['dt']}
            tend = float(fo['t'][-1] + fo['dt'][-1])
            cells = []
            self_err = None
            for md in M3:
                o = rp.replay(fo, md, k_solid=m.get('k_solid') or 0.271, T_ign=m.get('T_ign') or 756.0, rho=float(z['rho']))
                mt = rp.lighting_metrics(o[:, 0])
                OPEN[(prefix, mo, src, md)] = (mt, o)
                cells.append(f"{ms(mt.get('first'))} / {ms(mt.get('t50'))} / {ms(mt.get('t90'))} / {ms(mt.get('dur90'))}, never {mt['n_never']}")
                if md == src:
                    ig = np.array(m['ign'])
                    ok = (ig < tend) & (o[:, 0] < 1e9)
                    self_err = float(np.abs(o[ok, 0] - ig[ok]).max()) if ok.any() else float('nan')
            print(f"| {src} | {tend*1e3:.0f} | " + ' | '.join(cells) + f" | {self_err:.1e} |")
        print()


