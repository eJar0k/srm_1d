def load(g):
    d = {}
    p = RES / f'sm2_{g}.jsonl'
    if p.exists():
        for l in p.read_text().splitlines():
            if l.strip():
                m = json.loads(l)
                if 'error' not in m:
                    d[m['tag']] = m
    return d


A, X, H, D, C, K, G, KX = (load(g) for g in ['A', 'X', 'H', 'D', 'C', 'K', 'G', 'KX'])


def ms(v, nd=2):
    return '-' if v is None or (isinstance(v, float) and not np.isfinite(v)) else f'{v*1e3:.{nd}f}'


def f(v, nd=3):
    return '-' if v is None else f'{v:.{nd}f}'


def trunc_metrics(ign, t_end=None, n=None):
    """lighting metrics of an ignition-time array; cells lit after t_end count as never."""
    t = np.asarray(ign, dtype=float).copy()
    if t_end is not None:
        t[t > t_end] = rp.NEVER
    return rp.lighting_metrics(t)


def row_metrics(m):
    return [ms(m['t_first']), ms(m['t50']), ms(m['t90']), ms(m['dur90']), ms(m['t_last']), str(m['n_never'])]


def perf(m):
    mo = m['motor']
    if mo == 'balls':
        return f"{m['peak']:.3f} @ {m['t_peak']*1e3:.0f} ms | pk/tr {m['pk_trough']:.2f}, pk/mid {m['pk_mid']:.2f}"
    if mo == 'haseg':
        return f"late {m.get('late_peak', float('nan')):.3f} ({m.get('late_over_exp', float('nan')):.2f}x 6.44) @ {m.get('t_late_peak', 0):.2f} s | early {m['early_peak']:.2f}"
    return f"{m['peak']:.3f} @ {m['t_peak']*1e3:.1f} ms | pl {f(m.get('plateau'))}, pk/pl {f(m.get('peak_over_plateau'), 2)}"


